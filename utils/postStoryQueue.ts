/**
 * 「正文后暂停后续步骤」相关纯函数。
 *
 * 玩家诉求：正文（含文章优化）完成后不要自动跑变量生成、动态世界、规划分析、地图更新，
 * 先让玩家确认正文质量；不满意可以直接重ROLL，避免连锁消耗后面几个阶段的 AI 额度。
 */

export type 后续阶段名称 = '变量生成' | '动态世界' | '规划分析' | '地图更新';

export type 后续阶段可用性 = {
    变量生成?: boolean;
    动态世界?: boolean;
    规划分析?: boolean;
    地图更新?: boolean;
};

const 后续阶段顺序: 后续阶段名称[] = ['变量生成', '动态世界', '规划分析', '地图更新'];

/** 按固定展示顺序挑出真正会执行的阶段，避免摘要与实际执行顺序不一致。 */
export const 构建待执行阶段摘要 = (可用性?: 后续阶段可用性 | null): 后续阶段名称[] => {
    if (!可用性) return [];
    return 后续阶段顺序.filter((name) => 可用性[name] === true);
};

/** 给 UI 用的一句话说明；没有可执行阶段时明确告知，避免出现「点了没反应」的按钮。 */
export const 格式化待执行阶段说明 = (阶段列表?: 后续阶段名称[] | null): string => {
    const 列表 = Array.isArray(阶段列表) ? 阶段列表.filter(Boolean) : [];
    if (列表.length === 0) return '当前没有需要执行的后续阶段';
    return 列表.join(' / ');
};

/** 是否值得向玩家展示「继续后续步骤」入口：一个可执行阶段都没有时没必要打扰。 */
export const 需要展示后续步骤入口 = (阶段列表?: 后续阶段名称[] | null): boolean => (
    Array.isArray(阶段列表) && 阶段列表.length > 0
);
