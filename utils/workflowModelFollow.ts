export type 主剧情模型套用结果 = {
    ok: boolean;
    /** ok=false 时给用户看的处置建议 */
    原因?: string;
    /** 套用后的完整设置（已规范化） */
    设置: 接口设置结构;
    /** 实际被改写的阶段名（去重，按字段表顺序） */
    阶段: string[];
    渠道ID: string;
    渠道名称: string;
    模型: string;
};

/**
 * 把所有生成阶段的渠道与模型对齐到当前主剧情。
 *
 * 只改渠道 / 模型 / 独立地址 / 独立密钥，不改任何功能开关：
 * 「剧情回忆」「文章优化」「变量计算」的独立模型开关同时兼任该阶段的功能开关，
 * 关掉会让阶段直接不执行（见 `获取剧情回忆接口配置` 等函数），因此不能靠关开关来"跟随"。
 */
export const 套用主剧情模型到生成阶段 = (
    源设置: 接口设置结构,
    覆盖?: { 渠道ID?: string; 模型?: string }
): 主剧情模型套用结果 => {
    const 设置 = 规范化接口设置(源设置);
    const 渠道列表 = Array.isArray(设置.configs) ? 设置.configs : [];
    const 渠道ID = (覆盖?.渠道ID || 设置.activeConfigId || 渠道列表[0]?.id || '').trim();
    const 渠道 = 渠道列表.find((item) => item.id === 渠道ID) || 渠道列表[0] || null;
    const 主剧情模型 = (覆盖?.模型 || 获取主剧情接口配置(设置)?.model || '').trim();

    const 失败 = (原因: string): 主剧情模型套用结果 => ({
        ok: false,
        原因,
        设置,
        阶段: [],
        渠道ID: 渠道?.id || '',
        渠道名称: 渠道?.名称 || '',
        模型: 主剧情模型
    });

    if (!渠道?.id) return 失败('还没有配置任何接口渠道，请先在「接口设置」里添加渠道。');
    if (!主剧情模型) return 失败('主剧情模型还是空的，请先在「接口设置」里选好主剧情模型。');

    const 功能模型占位: 功能模型占位配置结构 = { ...设置.功能模型占位 };
    const 记录 = 功能模型占位 as unknown as Record<string, unknown>;
    for (const 字段 of 主剧情套用阶段字段表) {
        记录[字段.渠道键] = 渠道.id;
        记录[字段.模型键] = 主剧情模型;
        记录[字段.地址键] = '';
        记录[字段.密钥键] = '';
    }

    return {
        ok: true,
        设置: { ...设置, 功能模型占位 },
        阶段: Array.from(new Set(主剧情套用阶段字段表.map((item) => item.阶段))),
        渠道ID: 渠道.id,
        渠道名称: 渠道.名称 || '未命名渠道',
        模型: 主剧情模型
    };
};
