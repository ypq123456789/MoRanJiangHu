/** 生成一段纯文本摘要，供页面顶部总览或文档使用。 */
export const 生成模型配置建议总览 = (): string =>
    Object.values(功能模型配置建议)
        .map((item) => `【${item.功能名}】${item.作用}\n推荐：${item.推荐档位.均衡}\n注意：${item.常见误区}`)
        .join('\n\n');