/**
 * 各功能的模型配置建议（面向玩家的说明文案）。
 *
 * 与 `WorkflowGraphSettings.tsx` 的 `stageToggleTips` 并行使用：
 * 那一表回答「这个功能开了做什么」，本表回答「该给它配什么模型、怎么配」。
 *
 * 设计原则：
 * 1. **给建议，不替玩家做决定**——同一功能往往有多种合理档位，这里列出取舍而非唯一正确答案。
 * 2. **说清代价**——每条都注明「不独立配置会怎样」「配错会怎样」，避免玩家按功能名盲选。
 * 3. **推荐主线主流口径**——优先给出「省钱」「均衡」「效果」三档，而不是推荐小众模型。
 * 4. 文案随游戏版本走，修改前先看 `RELEASE_INFO` 里的相关约束，避免与实际行为打架。
 */

