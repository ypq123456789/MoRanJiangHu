const 环境 = {
    大地点: '中州大地',
    中地点: '青云山脉',
    小地点: '落霞坊市',
    具体地点: '外围街巷'
} as any;

describe('地图 NPC 层级归属', () => {
    it('位置只写到外围街巷的 NPC，不会被挂到同级的杂役院', () => {
        const social = [
            { 姓名: '俞月荷', 当前位置: '落霞坊市 > 外围街巷' }
        ];
        const scene = 构建地图空间场景(世界, 环境, social, '杨培强');

        const 俞月荷 = (scene.当前层人物 || []).find((person: any) => person.名称 === '俞月荷');
        expect(俞月荷).toBeTruthy();
        expect(俞月荷?.所在层级ID).toBe('DT-005');

        const 错挂 = (scene.当前层人物 || []).some((person: any) => person.所在层级ID === 'DT-006');
        expect(错挂).toBe(false);
    });

    it('位置写到建筑内部时，才挂到该建筑所在层级', () => {
        const social = [
            { 姓名: '俞月荷', 当前位置: '落霞坊市 > 天炉灵门杂役院' }
        ];
        const scene = 构建地图空间场景(
            世界,
            { ...环境, 具体地点: '天炉灵门杂役院' },
            social,
            '杨培强'
        );

        expect(scene.当前层级?.ID).toBe('DT-006');
        const 俞月荷 = (scene.当前层人物 || []).find((person: any) => person.名称 === '俞月荷');
        expect(俞月荷?.所在层级ID).toBe('DT-006');
    });
});
