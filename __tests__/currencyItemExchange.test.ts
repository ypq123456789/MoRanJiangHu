import { describe, expect, it } from 'vitest';
import { 计算货币物品兑换底层总值, 是否货币类物品 } from '../utils/currencyDisplay';
import { 规范化模式运行时配置 } from '../utils/modeRuntimeProfile';

// 武侠默认汇率：1 金元宝 = 100 银子，1 银子 = 1000 铜钱
// → 上层倍率 100000，中层倍率 1000，底层倍率 1
const 武侠配置 = 规范化模式运行时配置({
    identity: { baseMode: '武侠' },
    economy: {
        currencyTiers: {
            upperName: '金元宝',
            middleName: '银子',
            lowerName: '铜钱',
            upperToMiddleRate: 100,
            middleToLowerRate: 1000
        }
    }
} as any, '武侠');

describe('货币类物品兑换', () => {
    it('只把 货币: 前缀的物品识别为可兑换货币', () => {
        expect(是否货币类物品({ 类型: '货币:通用流通货币' })).toBe(true);
        expect(是否货币类物品({ 类型: '货币:银票' })).toBe(true);
        expect(是否货币类物品({ 类型: '消耗品' })).toBe(false);
        expect(是否货币类物品({ 类型: '武器' })).toBe(false);
        expect(是否货币类物品({ 类型: '' })).toBe(false);
        expect(是否货币类物品(null)).toBe(false);
    });

    it('未知货币名称按底层货币 1:1 兑换，不会变成花不掉的死物品', () => {
        // 玩家反馈的正是这种场景：商店买的“通用流通货币”此前完全无法使用
        const 总值 = 计算货币物品兑换底层总值(
            { 类型: '货币:通用流通货币', 名称: '通用流通货币', 堆叠数量: 250 },
            武侠配置,
            'wuxia'
        );
        expect(总值).toBe(250);
    });

    it('物品自带价值时优先按价值折算', () => {
        const 总值 = 计算货币物品兑换底层总值(
            { 类型: '货币:银票', 名称: '银票', 价值: 500, 堆叠数量: 3 },
            武侠配置,
            'wuxia'
        );
        expect(总值).toBe(1500);
    });

    it('命中世界观层级名时按该层级汇率折算', () => {
        const 总值 = 计算货币物品兑换底层总值(
            { 类型: '货币:银子', 名称: '碎银', 堆叠数量: 2 },
            武侠配置,
            'wuxia'
        );
        expect(总值).toBe(2000);
    });

    it('命中题材别名时按对应层级汇率折算', () => {
        // “灵晶”在题材别名表里属于中层货币
        const 总值 = 计算货币物品兑换底层总值(
            { 类型: '货币:灵晶', 名称: '灵晶', 堆叠数量: 2 },
            武侠配置,
            'wuxia'
        );
        expect(总值).toBe(2000);
    });

    it('数量为 0 或物品为空时不产生兑换值', () => {
        expect(计算货币物品兑换底层总值({ 类型: '货币:铜钱', 堆叠数量: 0 }, 武侠配置, 'wuxia')).toBe(0);
        expect(计算货币物品兑换底层总值(null, 武侠配置, 'wuxia')).toBe(0);
    });

    it('未标注堆叠数量时按 1 个计，与背包价值计算口径一致', () => {
        expect(计算货币物品兑换底层总值({ 类型: '货币:铜钱' }, 武侠配置, 'wuxia')).toBe(1);
        expect(计算货币物品兑换底层总值({ 类型: '货币:银子' }, 武侠配置, 'wuxia')).toBe(1000);
    });

    it('非有限数量（如 "1e309" / 非数字串）不产生兑换值，避免 Infinity 入账', () => {
        expect(计算货币物品兑换底层总值({ 类型: '货币:铜钱', 堆叠数量: '1e309' }, 武侠配置, 'wuxia')).toBe(0);
        expect(计算货币物品兑换底层总值({ 类型: '货币:铜钱', 堆叠数量: 'abc' }, 武侠配置, 'wuxia')).toBe(0);
    });

    it('单价×数量超出安全整数范围时返回 0，避免不精确金额写入角色金钱', () => {
        // 银子单价 1000 × 1e13 = 1e16 > Number.MAX_SAFE_INTEGER
        expect(计算货币物品兑换底层总值({ 类型: '货币:银子', 堆叠数量: 1e13 }, 武侠配置, 'wuxia')).toBe(0);
    });
});
