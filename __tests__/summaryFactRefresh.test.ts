import { describe, expect, it } from 'vitest';
import {
    合并摘要事实,
    摘要事实上限,
    早期事实上限,
    拆分摘要事实
} from '../hooks/useGame/groupChatTranscriptBudget';

/**
 * 维护者审查（PR #113 follow-up）两条小建议的回归：
 * 1. 事实被更完整的说法刷新后，要挪到末尾（算「最近」），不能占着原来靠前的位置；
 * 2. 一条新事实同时包含多条旧事实时，要把被包含的旧条目全部删掉，别只替换第一条留冗余。
 */
describe('合并摘要事实：刷新后挪到末尾', () => {
    it('新事实更完整时，删掉旧条目并追加到末尾', () => {
        const 合并 = 合并摘要事实(['药材已分好', '火候要小'], ['药材已分好，先煎的摆在炉边']);
        expect(合并).toEqual(['火候要小', '药材已分好，先煎的摆在炉边']);
        expect(合并[合并.length - 1]).toBe('药材已分好，先煎的摆在炉边');
    });

    it('刷新后它就在「最近」那一档里（拆分摘要事实的最近列表末尾）', () => {
        const 合并 = 合并摘要事实(['甲', '乙', '药材已分好'], ['药材已分好，先煎的摆在炉边']);
        const { 最近 } = 拆分摘要事实(合并);
        expect(最近[最近.length - 1]).toBe('药材已分好，先煎的摆在炉边');
    });
});

describe('合并摘要事实：一条新事实覆盖多条旧事实', () => {
    it('被同时包含的多条旧事实全部删掉，只留合并后的新条目', () => {
        const 合并 = 合并摘要事实(
            ['生姜两钱', '紫苏一把', '陈皮半钱', '薄荷另包'],
            ['生姜两钱、紫苏一把、陈皮半钱都齐了']
        );
        expect(合并).toContain('生姜两钱、紫苏一把、陈皮半钱都齐了');
        expect(合并.some(item => item === '生姜两钱')).toBe(false);
        expect(合并.some(item => item === '紫苏一把')).toBe(false);
        expect(合并.some(item => item === '陈皮半钱')).toBe(false);
        // 没被包含的那条不受影响
        expect(合并).toContain('薄荷另包');
    });
});

describe('合并摘要事实：其余去重规则不变', () => {
    it('旧条目包含新条目时保留旧的，不降级', () => {
        expect(合并摘要事实(['药材已分好，先煎的摆在炉边'], ['药材已分好']))
            .toEqual(['药材已分好，先煎的摆在炉边']);
    });

    it('完全相等只留一条', () => {
        expect(合并摘要事实(['薄荷另包'], ['薄荷另包'])).toHaveLength(1);
    });

    it('空白条目会被丢掉', () => {
        expect(合并摘要事实(['  ', ''], ['', '薄荷另包'])).toEqual(['薄荷另包']);
    });
});

describe('合并摘要事实：上限口径不变', () => {
    it('超过「最近 20 + 早期 40」时只留最后 60 条，最新追加的在末尾', () => {
        const 旧 = Array.from({ length: 60 }, (_, i) => `旧事实第${i + 1}条`);
        const 新 = Array.from({ length: 10 }, (_, i) => `新事实第${i + 1}条`);
        const 合并 = 合并摘要事实(旧, 新);
        expect(合并).toHaveLength(摘要事实上限 + 早期事实上限);
        expect(合并[合并.length - 1]).toBe('新事实第10条');
        expect(合并[合并.length - 10]).toBe('新事实第1条');
        // 20/40 分档口径不变：最近 20 条、早期 40 条
        const { 最近, 早期 } = 拆分摘要事实(合并);
        expect(最近).toHaveLength(摘要事实上限);
        expect(早期).toHaveLength(早期事实上限);
    });
});
