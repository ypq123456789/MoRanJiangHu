describe('TXT 编码自动探测（GBK 小说导入回归）', () => {
  it('GBK 文件能解出中文，不产生乱码', () => {
    const text = 解码文本文件字节(GBK样本);
    expect((text.match(/\uFFFD/g) || []).length).toBe(0);
    expect(text).toContain('第一章 江湖血路');
    expect(text).toContain('第一回 书院春意');
  });

  it('GBK 文件能按「第X章/回」拆分出多章（修前只出 1 章）', () => {
    const chapters = 从原始文本提取章节(建集(解码文本文件字节(GBK样本)));
    expect(chapters.length).toBeGreaterThan(1);
    expect(String(chapters[0].标题)).toContain('第一回');
  });

  it('强制按 UTF-8 解同一份字节会退化成 1 章（锁住回归根因）', () => {
    const broken = new TextDecoder('utf-8', { fatal: false }).decode(GBK样本);
    expect(从原始文本提取章节(建集(broken)).length).toBeLessThanOrEqual(1);
  });

  it('纯 UTF-8 文件原样返回，不被误判', () => {
    const utf8 = '第一章 江湖血路\n\n正文一。\n\n第二章 书院春意\n\n正文二。';
    expect(解码文本文件字节(new TextEncoder().encode(utf8))).toBe(utf8);
    expect(从原始文本提取章节(建集(utf8)).length).toBe(2);
  });

  it('UTF-8 BOM 被正确剥离', () => {
    const withBom = new Uint8Array([0xEF, 0xBB, 0xBF, ...new TextEncoder().encode('第一章 甲\n\n正文。')]);
    expect(解码文本文件字节(withBom).startsWith('第一章')).toBe(true);
  });

  it('空输入不抛异常', () => {
    expect(解码文本文件字节(null)).toBe('');
    expect(解码文本文件字节(new Uint8Array(0))).toBe('');
  });
});

